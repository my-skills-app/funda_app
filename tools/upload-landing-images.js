#!/usr/bin/env node
/**
 * Upload website screenshots to ImgBB and write js/screenshots.js
 *
 *   node tools/upload-landing-images.js
 */
'use strict';

const fs = require('fs');
const path = require('path');
const https = require('https');

const IMGBB_KEY = process.env.IMGBB_API_KEY;
const SOURCE_DIR = process.env.SCREENSHOTS_DIR
  || 'C:\\Users\\apple\\Downloads\\app images screen shorts';
const OUT_FILE = path.join(__dirname, '..', 'website', 'js', 'screenshots.js');

const FILES = [
  'photo_6188209225796882293_y.jpg',
  'photo_6188209225796882294_y.jpg',
  'photo_6188209225796882295_y.jpg',
  'photo_6188209225796882296_y.jpg',
  'photo_6188209225796882297_y.jpg',
  'photo_6188209225796882298_y.jpg',
];

function uploadBase64(base64, name) {
  return new Promise((resolve, reject) => {
    const body = new URLSearchParams({
      key: IMGBB_KEY,
      image: base64,
      name,
    }).toString();

    const req = https.request(
      {
        hostname: 'api.imgbb.com',
        path: '/1/upload',
        method: 'POST',
        headers: {
          'Content-Type': 'application/x-www-form-urlencoded',
          'Content-Length': Buffer.byteLength(body),
        },
      },
      (res) => {
        let data = '';
        res.on('data', (chunk) => { data += chunk; });
        res.on('end', () => {
          try {
            const json = JSON.parse(data);
            if (!json.success) {
              reject(new Error(json.error?.message || json.status_txt || 'Upload failed'));
              return;
            }
            resolve(json.data.display_url || json.data.url);
          } catch (e) {
            reject(e);
          }
        });
      }
    );
    req.on('error', reject);
    req.write(body);
    req.end();
  });
}

async function main() {
  if (!IMGBB_KEY) {
    throw new Error('Set IMGBB_API_KEY environment variable before running.');
  }
  const results = [];
  for (const file of FILES) {
    const full = path.join(SOURCE_DIR, file);
    if (!fs.existsSync(full)) {
      console.warn('Skip missing:', file);
      continue;
    }
    const base64 = fs.readFileSync(full).toString('base64');
    process.stdout.write('Uploading ' + file + '… ');
    const url = await uploadBase64(base64, file);
    console.log('OK');
    results.push({ file, url });
  }

  if (!results.length) {
    throw new Error('No images uploaded from ' + SOURCE_DIR);
  }

  const js =
    '/** Auto-generated by tools/upload-landing-images.js — do not edit by hand. */\n'
    + 'window.LANDING_SCREENSHOTS = '
    + JSON.stringify(results.map((r) => r.url), null, 2)
    + ';\n';

  fs.writeFileSync(OUT_FILE, js, 'utf8');
  console.log('\nWrote', OUT_FILE);
  results.forEach((r) => console.log(' -', r.url));
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
